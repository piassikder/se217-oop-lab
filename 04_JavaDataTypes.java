public class JavaDataTypes {
    public static void main(String[] args) {
        int a = 10;
        long b = 100000L;
        float c = 5.5f;
        double d = 10.25;
        boolean e = true;
        char f = 'P';

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
    }
}
